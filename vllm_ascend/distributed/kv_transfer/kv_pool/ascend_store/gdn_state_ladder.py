"""GDN boundary-state load ladder (C3): last-saved -> older-saved -> zero-recompute.

The hybrid consumer's external hit implies every group's boundary objects
exist at all boundaries <= the hit (the per-group-min hit check), so the
dominant ladder input is the newest boundary. A boundary whose state objects
fail to load (transfer/session failure — the T13 self-hit race class) demotes
the ladder one stage: an older boundary's state loads and the span
[loaded_boundary, fa_hit) is recomputed; no loadable boundary leaves the
zero-recompute rung (the B10/B14 empty-state final rung — nothing loaded, the
request recomputes from zero). Every demotion is LOUD (refuse-never-guess):
a demoted boundary emits HOLEMISS_STATE_ABSENT, a loaded boundary emits
HOLEMISS_STATE_LOAD, both byte-exact per the frozen v2 vocabulary
(holemiss-mooncake benchmarks/end_to_end/marker_vocab.py).

Single-group (text) layouts never enter this module: the plan builder
returns None for them (structural inertness, pinned by UT).
"""

from __future__ import annotations

import logging
from collections.abc import Callable, Iterable
from dataclasses import dataclass

logger = logging.getLogger(__name__)

RUNG_LAST_SAVED = 0
RUNG_OLDER_SAVED = 1
RUNG_ZERO_RECOMPUTE = 2

SOURCE_LAST_SAVED = "last_saved"
SOURCE_OLDER_SAVED = "older_saved"

REASON_MISSING = "missing"
REASON_LOAD_FAILED = "load_failed"
REASON_SAVE_DISABLED = "save_disabled"
REASON_LADDER_EXHAUSTED = "ladder_exhausted"


@dataclass(frozen=True)
class StateBoundary:
    """One align boundary's state objects across the GDN groups."""

    block_index: int
    boundary_tokens: int
    # group id -> the boundary's layerless object keys (all heads/stages)
    keys_by_group: dict[int, tuple[str, ...]]
    # group id -> the request's paged mamba block ids the objects load into
    blocks_by_group: dict[int, tuple[int, ...]]
    # group id -> a physical layer the group's state belongs to (marker field)
    first_layer_by_group: dict[int, int]


@dataclass(frozen=True)
class StateLoadPlan:
    req_id: str
    state_groups: tuple[int, ...]
    # boundaries OLDEST -> newest (block order); the ladder walks reversed
    boundaries: tuple[StateBoundary, ...]
    fa_hit_tokens: int
    # The SAVE channel's state (G12): use_layerwise=false still saves via the
    # bulk whole-object path (T13 control (a)) — never equate the two.
    save_enabled: bool


@dataclass
class BoundaryOutcome:
    """The result of one boundary load attempt."""

    attempted: bool
    loaded: bool
    payload_bytes: int = 0
    content_sha: str | None = None
    failed_block_ids: tuple[int, ...] = ()


@dataclass
class StateLoadResult:
    req_id: str
    rung: int
    source: str | None
    # token boundary whose state actually loaded; 0 on the zero-recompute rung
    loaded_boundary_tokens: int
    # (loaded_boundary, fa_hit): the span the engine must recompute for the
    # linear state (empty when the state loaded at the hit boundary)
    recompute_span: tuple[int, int]
    # G3's state_load_idx: paged blocks whose state was loaded (never zeroed)
    state_load_block_ids: frozenset[int] = frozenset()
    # Blocks whose load FAILED — the demoted boundaries' blocks on a loaded
    # rung (their state is regenerated by the recompute span, so the caller
    # dispositions them off the hybrid load-error raise), all state blocks
    # on the zero-recompute rung (which additionally surfaces them as load
    # errors for the whole-request recompute).
    failed_block_ids: frozenset[int] = frozenset()
    demoted: tuple[tuple[int, str], ...] = ()


def _emit_state_load(
    emit: Callable[[str], None],
    boundary: StateBoundary,
    group: int,
    source: str,
    rung: int,
    payload_bytes: int,
    content_sha: str | None,
) -> None:
    blocks = boundary.blocks_by_group.get(group) or (-1,)
    sha = content_sha if content_sha is not None else "none"
    emit(
        f"HOLEMISS_STATE_LOAD layer={boundary.first_layer_by_group[group]} group={group} "
        f"boundary={boundary.boundary_tokens} slot={blocks[0]} source={source} "
        f"rung={rung} bytes={payload_bytes} sha={sha}"
    )


def _emit_state_absent(
    emit: Callable[[str], None],
    boundary: StateBoundary,
    group: int,
    reason: str,
    rung: int,
) -> None:
    emit(
        f"HOLEMISS_STATE_ABSENT layer={boundary.first_layer_by_group[group]} group={group} "
        f"boundary={boundary.boundary_tokens} reason={reason} rung={rung}"
    )


def _all_blocks(plan: StateLoadPlan) -> frozenset[int]:
    return frozenset(
        block_id for boundary in plan.boundaries for ids in boundary.blocks_by_group.values() for block_id in ids
    )


def run_gdn_state_load_ladder(
    plan: StateLoadPlan,
    attempt_boundary: Callable[[StateBoundary], BoundaryOutcome],
    emit: Callable[[str], None],
) -> StateLoadResult:
    """Run the fallback ladder for one request's GDN boundary state.

    ``attempt_boundary`` loads ONE boundary's state objects into the request's
    paged blocks (the group-block payload channel) and reports the outcome;
    ``emit`` receives the byte-exact v2 marker lines. Demotions are LOUD: a
    log line per demoted boundary in addition to the marker.
    """

    def zero_recompute(demoted: tuple[tuple[int, str], ...]) -> StateLoadResult:
        return StateLoadResult(
            req_id=plan.req_id,
            rung=RUNG_ZERO_RECOMPUTE,
            source=None,
            loaded_boundary_tokens=0,
            recompute_span=(0, plan.fa_hit_tokens),
            failed_block_ids=_all_blocks(plan),
            demoted=demoted,
        )

    if not plan.state_groups or not plan.boundaries:
        # No GDN groups (text) or no boundary objects at all: nothing to load.
        return zero_recompute(())
    if not plan.save_enabled:
        logger.info(
            "HOLEMISS state ladder req=%s rung=%d reason=%s (save channel disabled)",
            plan.req_id,
            RUNG_ZERO_RECOMPUTE,
            REASON_SAVE_DISABLED,
        )
        newest = plan.boundaries[-1]
        for group in plan.state_groups:
            _emit_state_absent(emit, newest, group, REASON_SAVE_DISABLED, RUNG_ZERO_RECOMPUTE)
        return zero_recompute(((newest.boundary_tokens, REASON_SAVE_DISABLED),))

    demoted: list[tuple[int, str]] = []
    demoted_failed_blocks: list[int] = []
    newest_index = len(plan.boundaries) - 1
    for walk_index in range(newest_index, -1, -1):
        boundary = plan.boundaries[walk_index]
        outcome = attempt_boundary(boundary)
        if outcome.loaded:
            rung = RUNG_LAST_SAVED if walk_index == newest_index else RUNG_OLDER_SAVED
            source = SOURCE_LAST_SAVED if rung == RUNG_LAST_SAVED else SOURCE_OLDER_SAVED
            for group in plan.state_groups:
                _emit_state_load(emit, boundary, group, source, rung, outcome.payload_bytes, outcome.content_sha)
            if demoted:
                logger.info(
                    "HOLEMISS state ladder req=%s demoted=%s loaded_boundary=%d rung=%d",
                    plan.req_id,
                    demoted,
                    boundary.boundary_tokens,
                    rung,
                )
            return StateLoadResult(
                req_id=plan.req_id,
                rung=rung,
                source=source,
                loaded_boundary_tokens=boundary.boundary_tokens,
                recompute_span=(boundary.boundary_tokens, plan.fa_hit_tokens),
                state_load_block_ids=frozenset(
                    block_id for ids in boundary.blocks_by_group.values() for block_id in ids
                ),
                failed_block_ids=frozenset(demoted_failed_blocks),
                demoted=tuple(demoted),
            )
        reason = REASON_LOAD_FAILED if outcome.attempted else REASON_MISSING
        demoted.append((boundary.boundary_tokens, reason))
        demoted_failed_blocks.extend(outcome.failed_block_ids)
        next_rung = RUNG_OLDER_SAVED if walk_index > 0 else RUNG_ZERO_RECOMPUTE
        for group in plan.state_groups:
            _emit_state_absent(emit, boundary, group, reason, next_rung)
        logger.warning(
            "HOLEMISS state ladder req=%s boundary=%d demoted reason=%s next_rung=%d",
            plan.req_id,
            boundary.boundary_tokens,
            reason,
            next_rung,
        )
    logger.error("HOLEMISS state ladder req=%s ladder exhausted -> zero-recompute rung", plan.req_id)
    return zero_recompute(tuple(demoted))


def build_state_load_plan(
    req_id: str,
    state_groups: Iterable[int],
    boundaries: Iterable[StateBoundary],
    fa_hit_tokens: int,
    save_enabled: bool,
) -> StateLoadPlan | None:
    """Build the ladder plan; None when the layout has no GDN state groups.

    The None return is the text/32B structural-inertness gate: single-group
    layouts never construct a plan, so they never enter the ladder.
    """
    groups = tuple(sorted(set(state_groups)))
    if not groups:
        return None
    return StateLoadPlan(
        req_id=req_id,
        state_groups=groups,
        boundaries=tuple(boundaries),
        fa_hit_tokens=fa_hit_tokens,
        save_enabled=save_enabled,
    )
